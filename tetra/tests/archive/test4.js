const { chromium } = require('playwright');
const PAGE = require('../_page');
(async () => {
  const browser = await chromium.launch(PAGE.LAUNCH);
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 1366, height: 820 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error' && !/ERR_TUNNEL/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.goto(PAGE.URL); await page.waitForTimeout(700);
  await page.evaluate(() => { tetra.state.playing = false; });
  await page.click('[data-face="west"]'); await page.waitForTimeout(1900);
  await page.screenshot({ path: PAGE.out('s4_west.png') });
  console.log('face card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 500));
  await page.evaluate(() => tetra.select('island')); await page.waitForTimeout(1600);
  await page.screenshot({ path: PAGE.out('s4_island.png') });
  console.log('island card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 700));
  await page.evaluate(() => tetra.select('swamp')); await page.waitForTimeout(400);
  console.log('swamp card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 300));
  // edit lore on a no-lore place
  await page.click('.btnEdit'); await page.fill('#loreEdit', 'Swamp test'); await page.click('.btnSave'); await page.waitForTimeout(200);
  console.log('after save', await page.evaluate(() => document.querySelector('#placeBody .text').textContent + ' | ' + document.querySelector('#placeBody .chiptext').textContent));
  await page.click('.btnRestore'); await page.waitForTimeout(200);
  console.log('after restore', await page.evaluate(() => '[' + document.querySelector('#placeBody .text').textContent + '] ' + document.querySelector('#placeBody .chiptext').textContent + ' | ls=' + localStorage.getItem('tetra.lore.v1')));
  await page.click('#tabRegions'); await page.waitForTimeout(400);
  await page.evaluate(() => { document.querySelector('#codex .body').scrollTop = 420; }); await page.waitForTimeout(300);
  await page.screenshot({ path: PAGE.out('s4_regions.png') });
  await page.click('#tabWorld'); await page.evaluate(() => { document.querySelector('#codex .body').scrollTop = 1500; }); await page.waitForTimeout(300);
  await page.screenshot({ path: PAGE.out('s4_world.png') });
  console.log('markers', await page.evaluate(() => [...document.querySelectorAll('.marker')].map(m => m.textContent.trim() + (m.classList.contains('mark-x') ? '(X)' : ''))));
  console.log('json ok', await page.evaluate(() => { const j = JSON.parse(document.getElementById('worldJson').value); return j.regions.length + ' regions, chart stripped=' + (j.faces.west.chart === undefined) + ', kingdoms=' + j.regions.find(r => r.id === 'island').kingdoms.length; }));
  console.log('errors', JSON.stringify(errors));
  await ctx.close();
  const ctx2 = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
  const p2 = await ctx2.newPage(); const err2 = [];
  p2.on('pageerror', e => err2.push(String(e)));
  await p2.goto(PAGE.URL); await p2.waitForTimeout(600);
  await p2.evaluate(() => { tetra.state.playing = false; tetra.select('island'); }); await p2.waitForTimeout(1800);
  await p2.screenshot({ path: PAGE.out('s4_phone.png') });
  console.log('phone errors', JSON.stringify(err2));
  await ctx2.close(); await browser.close();
})();
