const { chromium } = require('playwright');
const PAGE = require('../_page');
(async () => {
  const browser = await chromium.launch(PAGE.LAUNCH);
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 1366, height: 820 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error' && !/ERR_TUNNEL/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.goto(PAGE.URL); await page.waitForTimeout(700);
  await page.evaluate(() => { tetra.state.playing = false; });
  await page.click('[data-face="far"]'); await page.waitForTimeout(2200); await page.screenshot({ path: PAGE.out('s8_far.png') });
  await page.click('[data-face="west"]'); await page.waitForTimeout(2200); await page.screenshot({ path: PAGE.out('s8_west.png') });
  await page.evaluate(() => tetra.select('greenia')); await page.waitForTimeout(1600); await page.screenshot({ path: PAGE.out('s8_greenia.png') });
  console.log('greenia card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 320).replace(/\n+/g, ' | '));
  await page.click('[data-face="south"]'); await page.waitForTimeout(2200); await page.screenshot({ path: PAGE.out('s8_south.png') });
  await page.evaluate(() => tetra.select('hotland')); await page.waitForTimeout(1600);
  console.log('hot card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 200).replace(/\n+/g, ' | '));
  await page.click('#tabWorld'); await page.evaluate(() => { document.querySelector('#codex .body').scrollTop = 1700; }); await page.waitForTimeout(300);
  await page.screenshot({ path: PAGE.out('s8_nations.png') });
  console.log('markers', await page.evaluate(() => [...document.querySelectorAll('.marker')].map(m => m.textContent.trim()).join(', ')));
  console.log('intro', await page.evaluate(() => document.querySelector('#paneWorld .tagline').textContent));
  console.log('json', await page.evaluate(() => { const j = JSON.parse(document.getElementById('worldJson').value); return j.regions.length + ' regions; hot=' + j.regions.find(r => r.id === 'hotland').name + '; tundra=' + j.regions.filter(r => /tundra/i.test(r.name)).length; }));
  console.log('errors', JSON.stringify(errors));
  await ctx.close();
  const ctx2 = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
  const p2 = await ctx2.newPage(); const err2 = [];
  p2.on('pageerror', e => err2.push(String(e)));
  await p2.goto(PAGE.URL); await p2.waitForTimeout(600);
  await p2.evaluate(() => { tetra.state.playing = false; tetra.select('beria'); }); await p2.waitForTimeout(1800);
  await p2.screenshot({ path: PAGE.out('s8_phone.png') });
  console.log('phone errors', JSON.stringify(err2));
  await ctx2.close(); await browser.close();
})();
