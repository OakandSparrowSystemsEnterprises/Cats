const { chromium } = require('playwright');
const PAGE = require('../_page');
(async () => {
  const browser = await chromium.launch(PAGE.LAUNCH);
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 1366, height: 820 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error' && !/ERR_TUNNEL/.test(m.text())) errors.push('console: ' + m.text()); });
  await page.goto(PAGE.URL); await page.waitForTimeout(700);
  await page.evaluate(() => { tetra.state.playing = false; });
  await page.screenshot({ path: PAGE.out('s5_canon.png') });
  await page.click('[data-face="south"]'); await page.waitForTimeout(1900); await page.screenshot({ path: PAGE.out('s5_south.png') });
  await page.click('[data-face="far"]'); await page.waitForTimeout(1900); await page.screenshot({ path: PAGE.out('s5_far.png') });
  console.log('far card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 400).replace(/\n+/g, ' | '));
  await page.evaluate(() => tetra.select('continent-south')); await page.waitForTimeout(1500); await page.screenshot({ path: PAGE.out('s5_continent.png') });
  console.log('continent card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 500).replace(/\n+/g, ' | '));
  await page.evaluate(() => tetra.select('hotland')); await page.waitForTimeout(1500);
  console.log('hot card', (await page.evaluate(() => document.getElementById('placeBody').innerText)).slice(0, 300).replace(/\n+/g, ' | '));
  await page.click('#tabWorld'); await page.evaluate(() => { document.querySelector('#codex .body').scrollTop = 1700; }); await page.waitForTimeout(300);
  await page.screenshot({ path: PAGE.out('s5_nations.png') });
  await page.click('#nations button'); await page.waitForTimeout(1500);
  console.log('after nation click', await page.evaluate(() => tetra.state.selected));
  console.log('markers', await page.evaluate(() => [...document.querySelectorAll('.marker')].map(m => m.textContent.trim() + (m.classList.contains('mark-x') ? '(X)' : m.classList.contains('mark-bolt') ? '(bolt)' : '')).join(', ')));
  console.log('json', await page.evaluate(() => { const j = JSON.parse(document.getElementById('worldJson').value); return j.regions.length + ' regions, nations groups ' + j.nations.length + ', far chart stripped=' + (j.faces.far.chart2 === undefined); }));
  console.log('errors', JSON.stringify(errors));
  await ctx.close();
  const ctx2 = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
  const p2 = await ctx2.newPage(); const err2 = [];
  p2.on('pageerror', e => err2.push(String(e)));
  await p2.goto(PAGE.URL); await p2.waitForTimeout(600);
  await p2.evaluate(() => { tetra.state.playing = false; tetra.select('warmia'); }); await p2.waitForTimeout(1800);
  await p2.screenshot({ path: PAGE.out('s5_phone.png') });
  console.log('phone errors', JSON.stringify(err2));
  await ctx2.close(); await browser.close();
})();
